#!/usr/bin/env bash
# Server side of deploy-remote.sh (#284), run on the server from the uploaded code:
#
#   provision.sh <deploy dir> < settings      # KEY=VALUE lines: REGION, addresses, SMTP, bucket, keys, webhook
#
# 1. Writes the region's settings file <deploy dir>/<region>.env (mode 600) from env.example, the values on stdin and
#    the database secrets. The file lives outside the code directory, so a new release replaces the code, not it.
# 2. Runs deploy.sh with the HTTPS reverse proxy (Compose profile `proxy`).
# 3. Installs the cron schedule: backup.sh nightly, healthcheck.sh every 5 minutes.
# 4. Checks GET /auth/v1/health and GET /rest/v1/ through the public HTTPS address.
#
# Idempotent: the database secrets (POSTGRES_PASSWORD, JWT_SECRET, ANON_KEY, SERVICE_ROLE_KEY, PG_META_CRYPTO_KEY)
# are generated by gen-env.sh on the first run only and kept on every later one — new ones would lock the stack out
# of its own data. The schedule is one marked block of the user's crontab, replaced on every run.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
. "$here/lib.sh"
deploy_dir=${1:?usage: provision.sh <deploy dir> < settings}

GENERATED_SECRETS=(POSTGRES_PASSWORD JWT_SECRET ANON_KEY SERVICE_ROLE_KEY PG_META_CRYPTO_KEY)

declare -A given=()
while IFS= read -r line || [[ -n $line ]]; do
  [[ -z $line ]] && continue
  # The line itself is never printed: it may hold a secret.
  [[ $line =~ ^([A-Z_][A-Z0-9_]*)=(.*)$ ]] || die "строка настроек не в виде KEY=VALUE"
  given[${BASH_REMATCH[1]}]=${BASH_REMATCH[2]}
done
region=${given[REGION]:-}
[[ $region =~ ^[a-z]{2}$ ]] || die "в настройках нет REGION (двухбуквенный код региона)"
for key in "${GENERATED_SECRETS[@]}"; do
  [[ -z ${given[$key]+set} ]] || die "$key создаётся на сервере и при деплое не передаётся"
done
for key in "${!given[@]}"; do
  [[ ${given[$key]} != *"'"* ]] || die "значение $key содержит апостроф (') — его нельзя записать в файл настроек"
done
export ENV_FILE=$deploy_dir/$region.env
work=$(mktemp -d)
tmp=""
# A half-written settings file (it holds secrets) never stays behind.
trap 'rm -rf "$work"; [[ -z $tmp ]] || rm -f "$tmp"' EXIT

write_settings() {
  local key line
  if [[ -f $ENV_FILE ]]; then
    local -A current=()
    read_env_file "$ENV_FILE" current
    for key in "${GENERATED_SECRETS[@]}"; do
      [[ -n ${current[$key]:-} ]] || die "в $ENV_FILE нет $key — восстановите файл из менеджера паролей"
      given[$key]=${current[$key]}
    done
    log "регион $region: файл настроек $ENV_FILE обновлён, секреты базы прежние"
  else
    log "регион $region: первый запуск — секреты базы созданы в $ENV_FILE (сохраните файл в менеджере паролей)"
  fi
  given[COMPOSE_PROFILES]=proxy

  # env.example with fresh secrets: they are used on the first run only.
  local base
  local -A written=()
  base=$("$here/gen-env.sh" REGION="$region")
  mkdir -p "$deploy_dir"
  tmp=$(mktemp "$ENV_FILE.XXXXXX") # mode 600 from the start
  # Every given value goes in single quotes, which Compose takes literally: `$`, `"` and backticks stay as they are.
  while IFS= read -r line; do
    if [[ $line =~ ^([A-Z_][A-Z0-9_]*)= && -n ${given[${BASH_REMATCH[1]}]+set} ]]; then
      key=${BASH_REMATCH[1]}
      written[$key]=1
      line="$key='${given[$key]}'"
    fi
    printf '%s\n' "$line"
  done <<< "$base" > "$tmp"
  for key in "${!given[@]}"; do
    [[ -n ${written[$key]+set} ]] || printf "%s='%s'\n" "$key" "${given[$key]}" >> "$tmp"
  done
  chmod 600 "$tmp"
  mv -f "$tmp" "$ENV_FILE"
}

# The user's crontab keeps whatever else it has; this region's block is replaced.
install_schedule() {
  local begin="# >>> lifeos-$REGION (deploy-remote.sh перезаписывает этот блок при каждом деплое)"
  local end="# <<< lifeos-$REGION" job="cd $here && ENV_FILE=$ENV_FILE" others
  others=$(crontab -l 2> /dev/null | awk -v b="# >>> lifeos-$REGION " -v e="$end" \
    'index($0, b) == 1 { skip = 1 } !skip { print } $0 == e { skip = 0 }' || true)
  {
    [[ -z $others ]] || printf '%s\n' "$others"
    printf '%s\n' "$begin" 'CRON_TZ=UTC' \
      '# копия базы каждую ночь в 22:00 UTC = 03:00 по Алматы; журнал: journalctl -t lifeos-backup' \
      "0 22 * * * $job ./backup.sh 2>&1 | logger -t lifeos-backup" \
      '# проверка стека каждые 5 минут, при проблеме — уведомление на ALERT_WEBHOOK_URL; журнал: journalctl -t lifeos-health' \
      "*/5 * * * * $job ./healthcheck.sh 2>&1 | logger -t lifeos-health" \
      "$end"
  } | crontab -
  log "расписание (crontab пользователя $(id -un)): backup.sh в 22:00 UTC, healthcheck.sh каждые 5 минут"
}

# The API as the world sees it: through the domain, the proxy and its certificate.
check_public_api() {
  local url=$SUPABASE_PUBLIC_URL tls=() auth='' rest=''
  if [[ $API_DOMAIN == localhost ]]; then
    # localhost cannot get a public certificate: Caddy signs it with its own CA, which this check then trusts.
    for _ in $(seq 1 30); do
      compose exec -T proxy cat /data/caddy/pki/authorities/local/root.crt > "$work/proxy-ca.crt" 2> /dev/null && break
      sleep 1
    done
    tls=(--cacert "$work/proxy-ca.crt")
  fi
  # Let's Encrypt may take a minute to issue the first certificate.
  for _ in $(seq 1 "${HTTPS_CHECK_TRIES:-60}"); do
    auth=$(http_status "$url/auth/v1/health" "$ANON_KEY" "${tls[@]}")
    rest=$(http_status "$url/rest/v1/" "$SERVICE_ROLE_KEY" "${tls[@]}")
    if [[ $auth == 200 && $rest == 200 ]]; then
      log "по HTTPS: GET /auth/v1/health и GET /rest/v1/ — 200 ($url)"
      return
    fi
    sleep 3
  done
  die "по HTTPS ($url) GET /auth/v1/health — $auth, GET /rest/v1/ — $rest (ожидалось 200): проверьте, что DNS домена указывает на сервер, а порты 80 и 443 открыты"
}

write_settings
load_env
"$here/deploy.sh"
install_schedule
check_public_api
log "регион $REGION: сервер готов, ревизия $(cat "$here/../../REVISION" 2> /dev/null || echo '?')"
